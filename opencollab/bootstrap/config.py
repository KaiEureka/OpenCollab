"""Pydantic-backed configuration loading.

Reads configs/.env from the current working directory or workspace, then falls
back to legacy .env files. Env-file parsing is built in, so python-dotenv is
not required.

Supported variables:
    OPENCOLLAB_MODEL      — default LLM model (e.g., "claude-sonnet-4-20250514")
    OPENCOLLAB_PROVIDER   — LLM provider ("openai", "anthropic")
    OPENCOLLAB_API_KEY    — API key (also reads OPENAI_API_KEY /
                            ANTHROPIC_API_KEY / DASHSCOPE_API_KEY)
    OPENCOLLAB_BASE_URL   — API base URL (also reads the selected provider's
                            OPENAI_BASE_URL or ANTHROPIC_BASE_URL)
    OPENCOLLAB_BUDGET     — default token budget
    OPENCOLLAB_TEMPERATURE — LLM sampling temperature (default 0.2)
    OPENCOLLAB_TOP_P      — LLM nucleus-sampling top_p (0..1; unset/empty → None,
                            i.e. the provider default, so the request is unchanged)
    OPENCOLLAB_MAX_OUTPUT_TOKENS — maximum tokens generated by one LLM call
    OPENCOLLAB_THINKING   — enable provider "thinking"/reasoning passthrough (bool, default off)
    OPENCOLLAB_THINKING_PARAMS — provider-native JSON object used when thinking
                            is on (OpenAI-compatible default
                            {"enable_thinking": true})
    OPENCOLLAB_LLM_TIMEOUT — provider request timeout in seconds
    OPENCOLLAB_LLM_STREAM_CHAT — consume chat completions as a stream so the
                            provider's reasoning text can be recorded (bool,
                            default off; off == today's request body)
    OPENCOLLAB_FILTER_MESSAGES — deprecated TUI compatibility setting (bool)
    OPENCOLLAB_CONFIG_FILE — explicit path to an env file
"""

from __future__ import annotations

import json
import os
import stat
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from opencollab.adapters.llm.providers import (
    is_anthropic,
    is_dashscope_endpoint,
    normalize_wire_protocol,
    required_env_key,
)
from opencollab.adapters.llm.types import DEFAULT_MAX_OUTPUT_TOKENS
from opencollab.adapters.safe_files import read_regular_text
from opencollab.bootstrap.environment_profiles import VMProfile

MAX_DOTENV_BYTES = 1024 * 1024

# Global sampling default, overridden by configuration and then the role.
DEFAULT_TEMPERATURE = 0.2

# ``None`` omits ``top_p`` from provider requests.
DEFAULT_TOP_P: float | None = None

# Default thinking parameters target OpenAI-compatible APIs. Native
# Anthropic needs explicit parameters matched to its model and output limit.
DEFAULT_THINKING = False
DEFAULT_THINKING_PARAMS: dict[str, Any] = {"enable_thinking": True}

_TRUTHY = frozenset({"1", "true", "yes", "on"})
_FALSY = frozenset({"0", "false", "no", "off"})

def _parse_bool(value: str | None, *, default: bool = False) -> bool:
    """Parse a supported boolean env string; default only on absence."""
    if value is None:
        return default
    normalized = value.strip().lower()
    if normalized in _TRUTHY:
        return True
    if normalized in _FALSY:
        return False
    raise ValueError(
        "boolean configuration must be one of "
        "1/true/yes/on or 0/false/no/off"
    )

def _parse_top_p(value: str | None) -> float | None:
    """Parse the top_p env string to ``float`` or ``None``.

    Unset or empty/whitespace-only → ``None`` (the provider default, request
    unchanged). A real number is returned as a float; range validation is left
    to the pydantic field so an out-of-range value fails loudly.
    """
    if value is None:
        return None
    stripped = value.strip()
    if not stripped:
        return None
    return float(stripped)

def _parse_thinking_params(value: str | None) -> dict[str, Any]:
    """Parse a JSON object string and reject unusable provider parameters."""
    if not value:
        return dict(DEFAULT_THINKING_PARAMS)
    try:
        parsed = json.loads(value)
    except (json.JSONDecodeError, TypeError) as exc:
        raise ValueError("OPENCOLLAB_THINKING_PARAMS must be valid JSON") from exc
    if not isinstance(parsed, dict):
        raise ValueError("OPENCOLLAB_THINKING_PARAMS must contain a JSON object")
    return parsed

def _validate_thinking_params(value: dict[str, Any]) -> dict[str, Any]:
    try:
        json.dumps(value, allow_nan=False)
    except (TypeError, ValueError) as exc:
        raise ValueError("thinking_params must be JSON-serializable") from exc
    return value

def resolve_thinking_params(value: dict[str, Any] | None) -> dict[str, Any]:
    """Copy explicit provider parameters, defaulting only when absent."""
    return dict(DEFAULT_THINKING_PARAMS if value is None else value)

def _optional_string(value: Any) -> Any:
    """Normalize optional credentials and endpoints before source selection."""
    if isinstance(value, str):
        return value.strip() or None
    return value

class ModelRoute(BaseModel):
    model_config = ConfigDict(extra="forbid", hide_input_in_errors=True)

    model: str = Field(min_length=1)
    provider: str = Field(default="openai", min_length=1)
    wire_protocol: str = "chat_completions"
    base_url: str | None = None
    api_key: str | None = Field(default=None, repr=False)
    auth_token: str | None = Field(default=None, repr=False)
    api_key_env: str | None = None
    context_window: int | None = Field(default=None, ge=1)
    request_pool: str | None = None
    request_capacity: int | None = Field(default=None, ge=1)

    @field_validator("model", "provider", "wire_protocol", mode="before")
    @classmethod
    def _strip_strings(cls, value: Any) -> Any:
        return value.strip() if isinstance(value, str) else value

    @field_validator("provider")
    @classmethod
    def _normalize_provider(cls, value: str) -> str:
        return value.lower()

    @field_validator("wire_protocol")
    @classmethod
    def _normalize_protocol(cls, value: str) -> str:
        return normalize_wire_protocol(value)

    @field_validator("base_url", "api_key", "auth_token", "api_key_env", "request_pool", mode="before")
    @classmethod
    def _optional_strings(cls, value: Any) -> Any:
        return _optional_string(value)

    @field_validator("context_window", "request_capacity", mode="before")
    @classmethod
    def _reject_boolean(cls, value: Any) -> Any:
        if isinstance(value, bool):
            raise ValueError("numeric configuration values must not be booleans")
        return value

    @model_validator(mode="after")
    def _validate_pool(self) -> ModelRoute:
        if (self.request_pool is None) != (self.request_capacity is None):
            raise ValueError("request_pool and request_capacity must be supplied together")
        if self.request_pool is not None and not os.path.isabs(self.request_pool):
            raise ValueError("request_pool must be an absolute local directory path")
        if is_anthropic(self.provider) and self.wire_protocol == "responses":
            raise ValueError("Responses wire protocol requires an OpenAI-compatible provider")
        return self


class OpenCollabConfig(BaseModel):
    """Runtime configuration for OpenCollab."""

    model_config = ConfigDict(extra="forbid", hide_input_in_errors=True)

    model: str = Field(default="gpt-4o", min_length=1)
    logical_model: str | None = None
    provider: str = Field(default="openai", min_length=1)
    wire_protocol: str = Field(default="chat_completions", min_length=1)
    api_key: str | None = Field(default=None, repr=False)
    auth_token: str | None = Field(default=None, repr=False)
    base_url: str | None = None
    model_routes: dict[str, ModelRoute] = Field(default_factory=dict, repr=False)
    vm: VMProfile | None = Field(default=None, repr=False)
    request_pool: str | None = None
    request_capacity: int | None = Field(default=None, ge=1)
    budget: int = Field(default=1_000_000, ge=1)
    temperature: float = Field(default=DEFAULT_TEMPERATURE, ge=0.0, le=2.0)
    top_p: float | None = Field(default=DEFAULT_TOP_P, ge=0.0, le=1.0)
    max_output_tokens: int = Field(default=DEFAULT_MAX_OUTPUT_TOKENS, ge=1)
    context_window: int | None = Field(default=None, ge=1)
    thinking: bool = Field(default=DEFAULT_THINKING)
    thinking_params: dict[str, Any] = Field(default_factory=lambda: dict(DEFAULT_THINKING_PARAMS))
    thinking_params_explicit: bool = False
    reasoning_effort: str | None = None
    llm_max_retries: int = Field(default=3, ge=0)
    llm_timeout: float = Field(default=600.0, gt=0, allow_inf_nan=False)
    llm_connect_timeout: float = Field(default=30.0, gt=0, allow_inf_nan=False)
    llm_first_event_timeout: float = Field(default=180.0, gt=0, allow_inf_nan=False)
    llm_stream_idle_timeout: float = Field(default=180.0, gt=0, allow_inf_nan=False)
    llm_stream_chat: bool = Field(default=False)
    provider_error_time_budget: float = Field(default=0.0, ge=0, allow_inf_nan=False)
    filter_messages: bool = Field(default=False)

    @field_validator("vm", mode="before")
    @classmethod
    def _vm_profile(cls, value: Any) -> Any:
        return json.loads(value) if isinstance(value, str) else value

    @model_validator(mode="before")
    @classmethod
    def _record_thinking_params_source(cls, value: Any) -> Any:
        if not isinstance(value, dict):
            return value
        params = value.get("thinking_params")
        if "thinking_params_explicit" not in value:
            value = dict(value)
            value["thinking_params_explicit"] = params is not None
        return value

    @model_validator(mode="after")
    def _record_edited_thinking_params_source(self) -> OpenCollabConfig:
        # Compare after the existing field validator normalizes JSON strings.
        if not self.thinking_params_explicit and self.thinking_params != DEFAULT_THINKING_PARAMS:
            self.thinking_params_explicit = True
        return self

    @field_validator(
        "request_capacity",
        "budget",
        "temperature",
        "top_p",
        "max_output_tokens",
        "context_window",
        "llm_max_retries",
        "llm_timeout",
        "llm_connect_timeout",
        "llm_first_event_timeout",
        "llm_stream_idle_timeout",
        "provider_error_time_budget",
        mode="before",
    )
    @classmethod
    def _reject_boolean_numbers(cls, value: Any) -> Any:
        if isinstance(value, bool):
            raise ValueError("numeric configuration values must not be booleans")
        return value

    @field_validator("model_routes", mode="before")
    @classmethod
    def _parse_routes(cls, value: Any) -> Any:
        if value is None:
            return {}
        if isinstance(value, str):
            value = json.loads(value)
        if not isinstance(value, dict) or any(
            not isinstance(key, str) or not key.strip() or key != key.strip() for key in value
        ):
            raise ValueError("model_routes must map non-empty model names to routes")
        return value

    @model_validator(mode="after")
    def _validate_request_pool(self) -> OpenCollabConfig:
        if (self.request_pool is None) != (self.request_capacity is None):
            raise ValueError("request_pool and request_capacity must be supplied together")
        if self.request_pool is not None and not os.path.isabs(self.request_pool):
            raise ValueError("request_pool must be an absolute local directory path")
        return self

    @field_validator("top_p", mode="before")
    @classmethod
    def _coerce_top_p(cls, value: Any) -> Any:
        if isinstance(value, str):
            return _parse_top_p(value)
        return value

    @field_validator("thinking", mode="before")
    @classmethod
    def _coerce_thinking(cls, value: Any) -> Any:
        if isinstance(value, str):
            return _parse_bool(value)
        return value

    @field_validator("thinking_params", mode="before")
    @classmethod
    def _coerce_thinking_params(cls, value: Any) -> Any:
        if isinstance(value, str):
            return _validate_thinking_params(_parse_thinking_params(value))
        if value is None:
            return dict(DEFAULT_THINKING_PARAMS)
        if isinstance(value, dict):
            return _validate_thinking_params(value)
        return value

    @field_validator("model", "provider", "wire_protocol", mode="before")
    @classmethod
    def _strip_required_strings(cls, value: Any) -> Any:
        if isinstance(value, str):
            return value.strip()
        return value

    @field_validator("provider")
    @classmethod
    def _normalize_provider(cls, value: str) -> str:
        return value.lower()

    @field_validator("wire_protocol")
    @classmethod
    def _normalize_wire_protocol(cls, value: str) -> str:
        return normalize_wire_protocol(value)

    @field_validator("reasoning_effort", mode="before")
    @classmethod
    def _normalize_reasoning_effort(cls, value: Any) -> Any:
        if value is None:
            return None
        normalized = str(value).strip().lower()
        if not normalized:
            return None
        allowed = {"none", "minimal", "low", "medium", "high", "xhigh", "max"}
        if normalized not in allowed:
            raise ValueError(
                "reasoning_effort must be none, minimal, low, medium, high, xhigh, or max"
            )
        return normalized

    @field_validator("api_key", "auth_token", "base_url", "request_pool", mode="before")
    @classmethod
    def _empty_string_as_none(cls, value: Any) -> Any:
        return _optional_string(value)

def _dotenv_value(value: str) -> str:
    """Remove unquoted whitespace-delimited comments, then outer quotes."""
    quote: str | None = None
    escaped = False
    for index, char in enumerate(value):
        if escaped:
            escaped = False
        elif quote == '"' and char == "\\":
            escaped = True
        elif quote:
            if char == quote:
                quote = None
        elif char in ("'", '"'):
            quote = char
        elif char == "#" and (index == 0 or value[index - 1].isspace()):
            value = value[:index].rstrip()
            break
    if len(value) >= 2 and value[0] == value[-1] and value[0] in ("'", '"'):
        return value[1:-1]
    return value

def load_dotenv(path: str | None = None) -> dict[str, str]:
    """Parse a .env file into a dict. Handles quotes and comments."""
    env_path = path or os.path.join(os.getcwd(), ".env")
    result: dict[str, str] = {}

    try:
        inspected = os.lstat(env_path)
    except FileNotFoundError:
        return result
    if not stat.S_ISREG(inspected.st_mode):
        raise ValueError(f"config env path is not a regular file: {env_path}")

    try:
        text = read_regular_text(env_path, max_bytes=MAX_DOTENV_BYTES)
    except UnicodeDecodeError as exc:
        raise ValueError(
            f"config env file encoding error: expected UTF-8: {env_path} "
            f"(byte {exc.start}: {exc.reason})"
        ) from exc
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        result[key] = _dotenv_value(value.strip())

    return result

def _candidate_env_paths(workspace: str | None = None) -> list[str]:
    """Return config file candidates in priority order."""
    explicit = os.environ.get("OPENCOLLAB_CONFIG_FILE")
    if explicit:
        if not Path(explicit).exists():
            raise ValueError(f"explicit config env path does not exist: {explicit}")
        return [explicit]

    bases: list[Path] = []
    if workspace:
        bases.append(Path(workspace))
    bases.append(Path.cwd())

    paths: list[str] = []
    seen: set[str] = set()
    for base in bases:
        for candidate in (base / "configs" / ".env", base / ".env"):
            key = str(candidate.resolve() if candidate.exists() else candidate.absolute())
            if key not in seen:
                paths.append(str(candidate))
                seen.add(key)
    return paths

def load_config_env(workspace: str | None = None) -> dict[str, str]:
    """Load env-file defaults from configs/.env and legacy .env locations.

    Earlier paths have higher priority.
    """
    values: dict[str, str] = {}
    for path in _candidate_env_paths(workspace):
        for key, value in load_dotenv(path).items():
            if not value.strip():
                continue
            values.setdefault(key, value)
    return values

def api_key_env_precedence(provider: str | None, base_url: str | None = None) -> tuple[str, ...]:
    """Resolve configured keys by endpoint before consulting generic variables."""
    if is_dashscope_endpoint(base_url):
        return ("DASHSCOPE_API_KEY", "OPENCOLLAB_API_KEY")
    if is_anthropic(provider):
        return ("ANTHROPIC_API_KEY", "OPENCOLLAB_API_KEY")
    return ("OPENCOLLAB_API_KEY", "OPENAI_API_KEY")

def accepted_api_key_envs(provider: str | None, base_url: str | None = None) -> list[str]:
    """Environment credentials recognized by the selected provider."""
    if is_dashscope_endpoint(base_url):
        names = ["OPENCOLLAB_API_KEY", "DASHSCOPE_API_KEY"]
    else:
        names = ["OPENCOLLAB_API_KEY", required_env_key(provider)]
    if is_anthropic(provider):
        names.append("ANTHROPIC_AUTH_TOKEN")
    return list(dict.fromkeys(names))

def missing_api_key(
    provider: str | None, api_key: str | None, base_url: str | None = None,
    auth_token: str | None = None,
) -> bool:
    """Whether the resolved key and provider environment lack credentials."""
    if api_key and api_key.strip():
        return False
    if is_anthropic(provider) and auth_token and auth_token.strip():
        return False
    for key in api_key_env_precedence(provider, base_url):
        value = os.environ.get(key)
        if value and value.strip():
            return False
    if is_anthropic(provider):
        auth_token = os.environ.get("ANTHROPIC_AUTH_TOKEN")
        if auth_token and auth_token.strip():
            return False
    return True

def resolve_provider_base_url(provider: str | None, base_url: str | None) -> str:
    """Select an endpoint from resolved config, including the provider default."""
    if base_url:
        return base_url
    return "https://api.anthropic.com" if is_anthropic(provider) else "https://api.openai.com/v1"

def build_config(workspace: str | None = None, overrides: dict[str, Any] | None = None) -> OpenCollabConfig:
    """Build and validate runtime configuration.

    Priority: environment variable > configs/.env > .env > built-in default
    """
    dotenv = load_config_env(workspace)

    def resolve(key: str, *fallback_keys: str, default: str | None = None) -> str | None:
        for source in (os.environ, dotenv):
            for name in (key, *fallback_keys):
                val = source.get(name)
                if val and val.strip():
                    return val
        return default

    def resolve_ordered(*keys: str, default: str | None = None) -> str | None:
        # For provider-specific secrets, key specificity matters more than
        # source. This prevents a generic exported OPENAI_API_KEY from being sent
        # to a provider-specific compatible endpoint such as DashScope.
        for key in keys:
            for source in (os.environ, dotenv):
                val = source.get(key)
                if val and val.strip():
                    return val
        return default

    selected_overrides: dict[str, Any] = {}
    for key, value in (overrides or {}).items():
        if key in {"api_key", "auth_token", "base_url"}:
            value = _optional_string(value)
        if value is not None:
            selected_overrides[key] = value
    provider_value = selected_overrides.get("provider") or resolve(
        "OPENCOLLAB_PROVIDER", default="openai"
    )
    provider_base_url_key = (
        "ANTHROPIC_BASE_URL" if is_anthropic(provider_value) else "OPENAI_BASE_URL"
    )
    base_url_value = (
        selected_overrides["base_url"]
        if "base_url" in selected_overrides
        else resolve("OPENCOLLAB_BASE_URL", provider_base_url_key)
    )
    api_key_names = api_key_env_precedence(provider_value, base_url_value)
    if is_anthropic(provider_value):
        api_key_names = tuple(name for name in api_key_names if name != "OPENCOLLAB_API_KEY")
    api_key_value = selected_overrides.get("api_key") or (
        None if selected_overrides.get("auth_token") else resolve_ordered(
            *api_key_names
        )
    )
    auth_token_value = (
        selected_overrides.get("auth_token") or resolve_ordered("ANTHROPIC_AUTH_TOKEN")
        if is_anthropic(provider_value) and not api_key_value else None
    )
    if is_anthropic(provider_value) and not api_key_value and not auth_token_value:
        api_key_value = resolve_ordered("OPENCOLLAB_API_KEY")

    defaults = {
        "model": "gpt-4o",
        "model_routes": None,
        "request_pool": None,
        "request_capacity": None,
        "vm": None,
        "wire_protocol": "chat_completions",
        "budget": "1000000",
        "temperature": str(DEFAULT_TEMPERATURE),
        "top_p": None,
        "max_output_tokens": str(DEFAULT_MAX_OUTPUT_TOKENS),
        "context_window": None,
        "thinking": str(DEFAULT_THINKING),
        "thinking_params": None,
        "reasoning_effort": None,
        "llm_max_retries": "3",
        "llm_timeout": "600",
        "llm_connect_timeout": "30",
        "llm_first_event_timeout": "180",
        "llm_stream_idle_timeout": "180",
        "llm_stream_chat": "false",
        "provider_error_time_budget": "0",
        "filter_messages": "false",
    }
    values: dict[str, Any] = {
        key: resolve(f"OPENCOLLAB_{key.upper()}", default=default)
        for key, default in defaults.items()
    }
    values.update(provider=provider_value, api_key=api_key_value,
                  auth_token=auth_token_value, base_url=base_url_value)
    values.update(selected_overrides)
    # Defaults share the same payload as an explicit DashScope protocol. Keep
    # its source before validation replaces None with that default mapping.
    values.setdefault("thinking_params_explicit", values["thinking_params"] is not None)
    config = OpenCollabConfig.model_validate(values)
    for route in config.model_routes.values():
        if route.api_key_env and not route.api_key:
            route.api_key = resolve_ordered(route.api_key_env)
            if not route.api_key:
                raise ValueError(f"model route API key environment variable is unset: {route.api_key_env}")
        if not route.api_key and not route.auth_token:
            names = api_key_env_precedence(route.provider, route.base_url)
            if is_anthropic(route.provider):
                names = tuple(name for name in names if name != "OPENCOLLAB_API_KEY")
            route.api_key = resolve_ordered(*names)
            if is_anthropic(route.provider) and not route.api_key:
                route.auth_token = resolve_ordered("ANTHROPIC_AUTH_TOKEN")
                if not route.auth_token:
                    route.api_key = resolve_ordered("OPENCOLLAB_API_KEY")
    return config

def get_config(workspace: str | None = None) -> dict[str, Any]:
    """Get resolved configuration as a dict for existing callers."""
    return build_config(workspace).model_dump()


def resolve_model_route(config: Mapping[str, Any], model: str | None = None) -> dict[str, Any]:
    resolved = dict(config)
    if model is None and config.get("logical_model") is not None:
        return resolved
    if model is not None:
        resolved["logical_model"] = None
    selected = config["model"] if model is None else model
    resolved["model"] = selected
    route = config.get("model_routes", {}).get(selected)
    if route is None:
        return resolved
    route = route if isinstance(route, ModelRoute) else ModelRoute.model_validate(route)
    values = route.model_dump(exclude={"api_key_env", "request_pool", "request_capacity"})
    resolved.update(values)
    if route.request_pool is not None:
        resolved.update(request_pool=route.request_pool, request_capacity=route.request_capacity)
    resolved["base_url"] = resolve_provider_base_url(route.provider, route.base_url)
    resolved["logical_model"] = selected
    return resolved
